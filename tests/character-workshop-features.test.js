"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),vm=require("node:vm"),path=require("node:path");
try{
 const dir=path.resolve(__dirname,".."),read=p=>fs.readFileSync(path.join(dir,p),"utf8");
 const files=["character-workshop-features.js","character-workshop-storage.js","character-workshop.js","workshop.html"];
 for(const f of files)assert.equal(read(f),read("docs/"+f),"GitHub Pages parity "+f);
 const html=read("workshop.html"),engine=read("character-workshop.js");
 for(const id of ["featureRow","featureHelp","restButton","longRestButton","resultNumbers"])
  assert.ok(html.includes('id="'+id+'"'),"Missing feature control "+id);
 assert.match(html,/character-workshop-features\.js\?v=features-20261027/);
 assert.match(engine,/FEATURES\.activate\(state,d,id\)/);
 assert.match(engine,/FEATURES\.rest\(state,derive\(state\),kind\)/);
 assert.match(engine,/FEATURES\.sneakAttack\(state\)/);
 assert.match(engine,/FEATURES\.rageBonus\(s\.level\)/);
 const ctx={console,Math,Date};vm.createContext(ctx);
 for(const file of ["character-workshop-catalog.js","character-workshop-features.js","character-workshop-storage.js","character-workshop.js"])
  new vm.Script(read(file),{filename:file}).runInContext(ctx);
 const e=ctx.CharacterWorkshopEngine,f=ctx.CharacterWorkshopFeatures;
 const s=()=>e.fresh(),d=x=>e.derive(x),get=(x,id)=>f.descriptors(x,d(x)).find(x=>x.id===id);
 assert.equal(f.rageUses(1),2);assert.equal(f.rageUses(3),3);assert.equal(f.rageUses(6),4);
 assert.equal(f.rageUses(12),5);assert.equal(f.rageUses(17),6);assert.equal(f.rageUses(20),Infinity);
 assert.equal(f.rageBonus(1),2);assert.equal(f.rageBonus(9),3);assert.equal(f.rageBonus(16),4);
 assert.equal(f.bardDie(1),6);assert.equal(f.bardDie(5),8);assert.equal(f.bardDie(10),10);assert.equal(f.bardDie(15),12);
 assert.equal(f.channelUses(1),1);assert.equal(f.channelUses(6),2);assert.equal(f.channelUses(18),3);
 const barbarian={...s(),classId:"barbarian",weapons:["greataxe"],shield:false,armor:"scale"};
 assert.equal(get(barbarian,"rage").remaining,3);
 assert.equal(f.activate(barbarian,d(barbarian),"rage").ok,true);
 assert.equal(barbarian.rageActive,true);
 assert.equal(get(barbarian,"rage").remaining,2);
 assert.equal(e.seededRoll(barbarian,"greataxe",()=>0).rows[0].damage,6,
  "d12 roll 1 + 3 STR + 2 rage");
 assert.equal(f.activate(barbarian,d(barbarian),"rage").ok,true);
 assert.equal(barbarian.rageActive,false,"Ending rage does not spend another charge");
 assert.equal(get(barbarian,"rage").remaining,2);
 assert.equal(e.seededRoll(barbarian,"greataxe",()=>0).rows[0].damage,4,
  "Ending Rage removes bonus");
 f.rest(barbarian,d(barbarian),"short");
 assert.equal(get(barbarian,"rage").remaining,2,"Short rest does not restore Rage");
 f.rest(barbarian,d(barbarian),"long");
 assert.equal(get(barbarian,"rage").remaining,3,"Long rest restores Rage");
 const bard={...s(),classId:"bard",level:5,scores:{...s().scores,CHA:18}};
 assert.equal(get(bard,"inspiration").max,4);
 assert.equal(get(bard,"inspiration").die,"d8");
 f.activate(bard,d(bard),"inspiration");
 assert.equal(get(bard,"inspiration").remaining,3);
 f.rest(bard,d(bard),"short");assert.equal(get(bard,"inspiration").remaining,4);
 const youngBard={...bard,level:4,featureSpent:{inspiration:1}};
 f.rest(youngBard,d(youngBard),"short");
 assert.equal(get(youngBard,"inspiration").remaining,3,"Bard inspiration only short-rest recovers from level 5");
 f.rest(youngBard,d(youngBard),"long");assert.equal(get(youngBard,"inspiration").remaining,4);
 const cleric={...s(),classId:"cleric",level:6};
 assert.equal(get(cleric,"channel").remaining,2);
 f.activate(cleric,d(cleric),"channel");assert.equal(get(cleric,"channel").remaining,1);
 f.rest(cleric,d(cleric),"short");assert.equal(get(cleric,"channel").remaining,2);
 const druid={...s(),classId:"druid",level:2};
 assert.equal(get(druid,"wildshape").remaining,2);
 assert.equal(f.activate(druid,d(druid),"wildshape").ok,true);
 assert.equal(get(druid,"wildshape").remaining,1);
 assert.equal(d(druid).maxHP,17,"Wild Shape does not overwrite humanoid stats");
 const monk={...s(),classId:"monk",level:5};
 assert.equal(get(monk,"ki").max,5);
 for(let i=0;i<5;i++)assert.equal(f.activate(monk,d(monk),"ki").ok,true);
 assert.equal(get(monk,"ki").remaining,0);
 assert.equal(f.activate(monk,d(monk),"ki").ok,false,"Cannot overspend Ki");
 f.rest(monk,d(monk),"short");assert.equal(get(monk,"ki").remaining,5);
 const paladin={...s(),classId:"paladin",level:5};
 assert.equal(get(paladin,"layhands").max,25);
 assert.equal(f.activate(paladin,d(paladin),"layhands").result.heal,5);
 assert.equal(get(paladin,"layhands").remaining,20);
 assert.equal(get(paladin,"paladinchannel").remaining,1);
 f.activate(paladin,d(paladin),"paladinchannel");
 f.rest(paladin,d(paladin),"short");assert.equal(get(paladin,"paladinchannel").remaining,1);
 assert.equal(get(paladin,"layhands").remaining,20,"Short rest does not recover Lay on Hands");
 f.rest(paladin,d(paladin),"long");assert.equal(get(paladin,"layhands").remaining,25);
 const sorcerer={...s(),classId:"sorcerer",level:3};
 assert.equal(get(sorcerer,"sorcery").remaining,3);
 const warlock={...s(),classId:"warlock",level:5};
 assert.equal(get(warlock,"pactslot").remaining,2);
 assert.equal(f.activate(warlock,d(warlock),"pactslot").ok,true);
 assert.equal(get(warlock,"pactslot").remaining,1);
 f.rest(warlock,d(warlock),"short");assert.equal(get(warlock,"pactslot").remaining,2);
 const rogue={...s(),classId:"rogue",level:5};
 const sneak=f.sneakAttack(rogue,()=>0);
 assert.equal(sneak.dice,"3d6");
 assert.equal(sneak.roll,3);
 assert.match(sneak.note,/qualifying hit/);
 const notRogue=f.sneakAttack(s());assert.equal(notRogue.type,"notice");
 const fighter=s();assert.equal(f.descriptors(fighter,d(fighter)).length,0,"Fighter existing buttons unchanged");
 assert.equal(f.activate(fighter,d(fighter),"rage").ok,false,"No cross-class feature injection");
 assert.throws(()=>f.rest(fighter,d(fighter),"medium"));
 console.log("2014 one-touch class resources: Rage damage, Bardic Inspiration, Channel Divinity, Wild Shape, Ki, Lay on Hands, Pact Slots, Sorcery and Rogue Sneak Attack passed.");
}catch(err){console.error("Feature resources regression failure",err);process.exitCode=1;}
